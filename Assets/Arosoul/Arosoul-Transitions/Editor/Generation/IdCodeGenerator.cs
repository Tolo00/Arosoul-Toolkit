using System.Collections.Generic;
using System.Text;

namespace Arosoul.Transitions.Editor
{
    public readonly struct IdEntry
    {
        public readonly string Name;
        public readonly string Expression;

        public IdEntry(string name, string expression)
        {
            Name = name;
            Expression = expression;
        }
    }

    public sealed class IdClassSpec
    {
        public string ClassName;
        public string TypeName;
        public string Summary;
        public List<IdEntry> Entries = new List<IdEntry>();

        public IdClassSpec(string className, string typeName, string summary)
        {
            ClassName = className;
            TypeName = typeName;
            Summary = summary;
        }
    }

    /// <summary>
    /// Generates source for static classes of readonly id constants.
    /// Names must already be valid and unique, see <see cref="IdentifierUtility"/>.
    /// </summary>
    public static class IdCodeGenerator
    {
        public static string Generate(string @namespace, IReadOnlyList<string> usings, IReadOnlyList<IdClassSpec> classes, string source)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// This file is generated by ").Append(source).Append(".\n");
            sb.Append("// Do not edit manually, changes will be overwritten.\n");
            sb.Append("// </auto-generated>\n\n");

            for (int i = 0; i < usings.Count; i++)
                sb.Append("using ").Append(usings[i]).Append(";\n");
            if (usings.Count > 0) sb.Append("\n");

            sb.Append("namespace ").Append(@namespace).Append("\n{\n");
            for (int c = 0; c < classes.Count; c++)
            {
                var spec = classes[c];
                sb.Append("    /// <summary>").Append(spec.Summary).Append("</summary>\n");
                sb.Append("    public static class ").Append(spec.ClassName).Append("\n    {\n");
                for (int e = 0; e < spec.Entries.Count; e++)
                {
                    var entry = spec.Entries[e];
                    sb.Append("        public static readonly ").Append(spec.TypeName).Append(' ')
                      .Append(entry.Name).Append(" = ").Append(entry.Expression).Append(";\n");
                }
                sb.Append("    }\n");
                if (c < classes.Count - 1) sb.Append("\n");
            }
            sb.Append("}\n");
            return sb.ToString();
        }
    }
}
