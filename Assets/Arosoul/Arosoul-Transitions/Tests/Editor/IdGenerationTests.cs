using System.Collections.Generic;
using NUnit.Framework;
using Arosoul.Transitions.Editor;

namespace Arosoul.Transitions.Tests
{
    public class IdentifierUtilityTests
    {
        [TestCase("Fade", "Fade")]
        [TestCase("Wipe Left", "WipeLeft")]
        [TestCase("fade-in", "fadeIn")]
        [TestCase("2D Fade", "_2DFade")]
        [TestCase("class", "_class")]
        [TestCase("  ", "Unnamed")]
        [TestCase("!!!", "Unnamed")]
        [TestCase(null, "Unnamed")]
        public void Sanitize_ProducesValidIdentifier(string input, string expected)
        {
            Assert.AreEqual(expected, IdentifierUtility.Sanitize(input));
        }

        [Test]
        public void MakeUnique_AppendsSuffixToDuplicates()
        {
            var result = IdentifierUtility.MakeUnique(new[] { "Fade", "Fade", "Slide", "Fade" });
            CollectionAssert.AreEqual(new[] { "Fade", "Fade_2", "Slide", "Fade_3" }, result);
        }

        [Test]
        public void MakeUnique_TreatsDifferentSpellingsOfSameIdentifierAsDuplicates()
        {
            var result = IdentifierUtility.MakeUnique(new[] { "Wipe Left", "WipeLeft" });
            CollectionAssert.AreEqual(new[] { "WipeLeft", "WipeLeft_2" }, result);
        }
    }

    public class StableIdAllocatorTests
    {
        [Test]
        public void Allocate_KeepsExistingIds()
        {
            var result = StableIdAllocator.Allocate(new[] { 3, 1, 2 });
            CollectionAssert.AreEqual(new[] { 3, 1, 2 }, result);
        }

        [Test]
        public void Allocate_AssignsNewIdsAboveMax()
        {
            var result = StableIdAllocator.Allocate(new[] { 0, 5, 0 });
            CollectionAssert.AreEqual(new[] { 6, 5, 7 }, result);
        }

        [Test]
        public void Allocate_ReassignsDuplicates_FirstKeepsId()
        {
            var result = StableIdAllocator.Allocate(new[] { 2, 2, 1 });
            Assert.AreEqual(2, result[0]);
            Assert.AreEqual(1, result[2]);
            Assert.AreEqual(3, result[1]);
        }

        [Test]
        public void Allocate_IdsAreUnique()
        {
            var result = StableIdAllocator.Allocate(new[] { 0, 0, 4, 4, 0, -1 });
            Assert.AreEqual(result.Length, new HashSet<int>(result).Count);
            foreach (int id in result) Assert.Greater(id, 0);
        }
    }

    public class IdCodeGeneratorTests
    {
        [Test]
        public void Generate_ContainsConstantsAndNamespace()
        {
            var spec = new IdClassSpec("TransitionIds", "TransitionId", "Ids.");
            spec.Entries.Add(new IdEntry("Fade", "new TransitionId(1)"));
            spec.Entries.Add(new IdEntry("Slide", "new TransitionId(2)"));

            string code = IdCodeGenerator.Generate("Arosoul.Generated", new[] { "Arosoul.Transitions" }, new[] { spec }, "Test");

            StringAssert.Contains("namespace Arosoul.Generated", code);
            StringAssert.Contains("using Arosoul.Transitions;", code);
            StringAssert.Contains("public static class TransitionIds", code);
            StringAssert.Contains("public static readonly TransitionId Fade = new TransitionId(1);", code);
            StringAssert.Contains("public static readonly TransitionId Slide = new TransitionId(2);", code);
            StringAssert.Contains("<auto-generated>", code);
        }

        [Test]
        public void Generate_IsDeterministic()
        {
            var spec = new IdClassSpec("A", "T", "S");
            spec.Entries.Add(new IdEntry("X", "new T(1)"));

            string a = IdCodeGenerator.Generate("N", new string[0], new[] { spec }, "Test");
            string b = IdCodeGenerator.Generate("N", new string[0], new[] { spec }, "Test");
            Assert.AreEqual(a, b);
        }
    }
}
