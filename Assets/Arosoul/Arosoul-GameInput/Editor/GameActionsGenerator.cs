using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Arosoul.GameInput.EditorTools {

    /// <summary>
    /// Writes GameActions.cs from the Input Actions asset: one nested class per action map, one typed field per action.
    /// Runs automatically when the asset or the config changes, so there is nothing to register by hand.
    ///
    /// Action type rules (set them in Unity's Input Actions editor):
    ///   name ends with "Priority"          => PriorityAction (e.g. "BackPriority")
    ///   expected control type Vector2      => Vector2Action
    ///   expected control type Axis/Analog  => AnalogAction
    ///   Button / not set                   => ButtonAction
    /// </summary>
    internal static class GameActionsGenerator {
        const string FileName = "GameActions.cs";
        const string PrioritySuffix = "Priority";

        static readonly HashSet<string> Keywords = new HashSet<string> {
            "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue","decimal",
            "default","delegate","do","double","else","enum","event","explicit","extern","false","finally","fixed","float","for",
            "foreach","goto","if","implicit","in","int","interface","internal","is","lock","long","namespace","new","null","object",
            "operator","out","override","params","private","protected","public","readonly","ref","return","sbyte","sealed","short",
            "sizeof","stackalloc","static","string","struct","switch","this","throw","true","try","typeof","uint","ulong",
            "unchecked","unsafe","ushort","using","virtual","void","volatile","while"
        };

        static bool queued;

        [MenuItem("Tools/Arosoul/GameInput/Generate Actions", priority = 103)]
        static void MenuGenerate() => Generate(true);

        public static GameInputConfig FindConfig() {
            foreach (string guid in AssetDatabase.FindAssets("t:GameInputConfig")) {
                var config = AssetDatabase.LoadAssetAtPath<GameInputConfig>(AssetDatabase.GUIDToAssetPath(guid));
                if (config != null) return config;
            }
            return null;
        }

        public static void QueueGenerate() {
            if (queued) return;
            queued = true;
            EditorApplication.delayCall += () => { queued = false; Generate(false); };
        }

        public static void Generate(bool verbose) => Generate(FindConfig(), verbose);

        public static void Generate(GameInputConfig config, bool verbose) {
            if (config == null) {
                if (verbose) Debug.LogWarning("[GameInput] No GameInputConfig found. Use Tools > Arosoul > GameInput > Create Config.");
                return;
            }
            if (config.Actions == null) {
                if (verbose) Debug.LogWarning("[GameInput] Assign an Input Actions asset to the GameInputConfig first.", config);
                return;
            }
            if (!AssetDatabase.GetAssetPath(config).Replace('\\', '/').Contains("/Resources/")) {
                Debug.LogWarning("[GameInput] The GameInputConfig must be in a Resources folder, otherwise it can't be found at runtime.", config);
            }

            string code = Build(config);
            string folder = config.GeneratedFolder.TrimEnd('/');
            string path = folder + "/" + FileName;

            if (File.Exists(path) && File.ReadAllText(path) == code) {
                if (verbose) Debug.Log("[GameInput] GameActions is up to date.");
                return;
            }

            Directory.CreateDirectory(folder);
            File.WriteAllText(path, code, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            Debug.Log($"[GameInput] Generated {path}");
        }

        internal static string Build(GameInputConfig config) {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     Generated by Arosoul GameInput from the Input Actions asset assigned in GameInputConfig.");
            sb.AppendLine("//     Changes to this file are overwritten. Edit the Input Actions asset instead.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("using Arosoul.GameInput;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine();
            // GameActions lives in the global namespace (like SceneIds and TransitionIds), so game code needs no using directive for it.
            sb.AppendLine("/// <summary>Typed access to every action of the Input Actions asset assigned in GameInputConfig.</summary>");
            sb.AppendLine("public static class GameActions");
            sb.AppendLine("{");

            var all = new List<string>();
            // These names are already used by members of the containing GameActions class.
            var usedMaps = new HashSet<string> { "All", "Register", "GameActions" };

            bool firstMap = true;
            foreach (var map in config.Actions.actionMaps) {
                if (config.IsExcludedMap(map.name)) continue;

                string mapId = Unique(Identifier(map.name), usedMaps);
                if (!firstMap) sb.AppendLine();
                firstMap = false;
                sb.AppendLine($"    /// <summary>Action map '{map.name}'.</summary>");
                sb.AppendLine($"    public static class {mapId}");
                sb.AppendLine("    {");

                var usedActions = new HashSet<string> { "Enable", "Disable" };
                foreach (var action in map.actions) {
                    string type = WrapperTypeFor(action);
                    if (type == null) {
                        Debug.LogWarning($"[GameInput] Skipping '{map.name}/{action.name}': expected control type '{action.expectedControlType}' is not supported (use Button, Vector2 or Axis).", config);
                        continue;
                    }

                    string id = Unique(Identifier(action.name), usedActions);
                    sb.AppendLine($"        public static readonly {type} {id} = new {type}({Literal(map.name)}, {Literal(action.name)});");
                    all.Add($"{mapId}.{id}");
                }

                sb.AppendLine();
                sb.AppendLine($"        public static void Enable() => GameInput.SetMapEnabled({Literal(map.name)}, true);");
                sb.AppendLine($"        public static void Disable() => GameInput.SetMapEnabled({Literal(map.name)}, false);");
                sb.AppendLine("    }");
            }

            sb.AppendLine();
            sb.AppendLine("    private static readonly GameAction[] All =");
            sb.AppendLine("    {");
            foreach (string a in all) sb.AppendLine($"        {a},");
            sb.AppendLine("    };");
            sb.AppendLine();
            sb.AppendLine("    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]");
            sb.AppendLine("    private static void Register() => GameInputRuntime.Register(All);");
            sb.AppendLine("}");
            return sb.ToString().Replace("\r\n", "\n");
        }

        /// <summary>Name of the generated wrapper type for an action, or null if its control type is not supported.</summary>
        internal static string WrapperTypeFor(InputAction action) {
            if (action.name.Length > PrioritySuffix.Length && action.name.EndsWith(PrioritySuffix, StringComparison.Ordinal)) return "PriorityAction";

            switch (action.expectedControlType ?? string.Empty) {
                case "Vector2": return "Vector2Action";
                case "Axis":
                case "Analog": return "AnalogAction";
                case "":
                case "Button":
                case "Digital": return "ButtonAction";
                default: return null;
            }
        }

        static string Identifier(string name) {
            var sb = new StringBuilder();
            foreach (char c in name) if (char.IsLetterOrDigit(c) || c == '_') sb.Append(c);
            if (sb.Length == 0) sb.Append('_');
            if (char.IsDigit(sb[0])) sb.Insert(0, '_');

            string id = sb.ToString();
            return Keywords.Contains(id) ? id + "_" : id;
        }

        static string Unique(string id, HashSet<string> used) {
            string result = id;
            for (int n = 2; !used.Add(result); n++) result = id + n;
            return result;
        }

        static string Literal(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }

    /// <summary>Regenerates GameActions whenever an Input Actions asset or a config asset is (re)imported.</summary>
    internal sealed class GameActionsPostprocessor : AssetPostprocessor {
        static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom) {
            foreach (string path in imported.Concat(moved)) {
                if (path.EndsWith(".inputactions", StringComparison.OrdinalIgnoreCase) || path.EndsWith(".asset", StringComparison.OrdinalIgnoreCase)) {
                    var config = GameActionsGenerator.FindConfig();
                    if (config != null && config.AutoGenerate) GameActionsGenerator.QueueGenerate();
                    return;
                }
            }
        }
    }

}
